-- 微信支付记录表
CREATE TABLE IF NOT EXISTS `lin_wechat_payment` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `payment_no` varchar(64) NOT NULL COMMENT '支付订单号（商户侧）',
  `order_id` int(11) NOT NULL COMMENT '业务订单ID（关联lin_lb_listdiagnosisproject）',
  `user_id` int(11) NOT NULL COMMENT '用户ID',
  `hospital_id` int(11) NOT NULL COMMENT '医院ID',
  `amount` decimal(10,2) NOT NULL COMMENT '支付金额（元）',
  `total_fee` int(11) NOT NULL COMMENT '支付金额（分）',
  `status` tinyint(4) NOT NULL DEFAULT '0' COMMENT '支付状态 (0=未支付, 1=已支付, 2=已关闭, 3=已退款)',
  `transaction_id` varchar(64) DEFAULT NULL COMMENT '微信支付订单号',
  `prepay_id` varchar(64) DEFAULT NULL COMMENT '微信预支付ID',
  `pay_type` varchar(20) DEFAULT 'JSAPI' COMMENT '支付类型 (JSAPI=小程序支付)',
  `openid` varchar(128) DEFAULT NULL COMMENT '微信用户openid',
  `trade_type` varchar(20) DEFAULT NULL COMMENT '交易类型',
  `trade_state` varchar(20) DEFAULT NULL COMMENT '交易状态',
  `paid_at` datetime DEFAULT NULL COMMENT '支付完成时间',
  `create_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_at` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `notify_time` datetime DEFAULT NULL COMMENT '支付通知时间',
  `refund_id` varchar(64) DEFAULT NULL COMMENT '退款ID',
  `refund_amount` decimal(10,2) DEFAULT NULL COMMENT '退款金额',
  `refund_status` varchar(20) DEFAULT NULL COMMENT '退款状态',
  `body` varchar(255) DEFAULT NULL COMMENT '商品描述',
  `detail` varchar(255) DEFAULT NULL COMMENT '商品详情',
  `attach` varchar(255) DEFAULT NULL COMMENT '附加数据',
  `out_trade_no` varchar(64) DEFAULT NULL COMMENT '商户订单号',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_payment_no` (`payment_no`),
  KEY `idx_order_id` (`order_id`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_transaction_id` (`transaction_id`),
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='微信支付记录表';
