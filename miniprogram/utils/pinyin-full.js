/**
 * 将汉字转换为拼音全拼
 * @param {String} chinese - 中文字符串
 * @returns {String} 拼音字符串（大写，无空格）
 */
function convertToPinyin(chinese) {
  if (!chinese) return '';

  // 如果是英文字符串，直接转大写返回
  if (/^[a-zA-Z\s]+$/.test(chinese)) {
    return chinese.toUpperCase().replace(/\s+/g, '');
  }

  let result = '';

  for (let i = 0; i < chinese.length; i++) {
    const char = chinese[i];

    // 如果是英文字母或数字，直接保留
    if (/[a-zA-Z0-9]/.test(char)) {
      result += char.toUpperCase();
      continue;
    }

    // 如果是空格，跳过
    if (/\s/.test(char)) {
      continue;
    }

    // 查找汉字拼音
    const pinyin = PINYIN_DICT[char];
    if (pinyin) {
      result += pinyin;
    } else {
      // 未找到拼音，使用原字符（这种情况很少，对于非常用汉字）
      console.warn(`[Pinyin] 未找到汉字拼音: ${char}`);
      result += char;
    }
  }

  return result;
}

